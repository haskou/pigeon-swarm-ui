import { KeyPair } from '@haskou/pigeon-swarm-crypto';
import { mock } from 'jest-mock-extended';

import type { Session } from '../../../../../contexts/identities/infrastructure/session/Session';
import type { HttpJsonClient } from '../../../../../shared/infrastructure/http/HttpJsonClient';

import { ConversationMapper } from '../../../../../contexts/conversations/infrastructure/http/ConversationMapper';
import { PigeonConversationsApi } from '../../../../../contexts/conversations/infrastructure/http/PigeonConversationsApi';
import { RequestSigner } from '../../../../../shared/infrastructure/http/RequestSigner';
import vectors from '../../../../fixtures/message-read-proof-vectors.json';

// The fixture is generated by the node (MessageReadProofVerifier). The read
// proof is the reader identity signature over the canonical PUT payload, so
// markReadUntil must send the same bytes. Ed25519 is deterministic.
// The UI only sends read-until as PUT, so only accepted cases are pinned here.
type Case = (typeof vectors.cases)[number];

function sessionFromVectorKey(): Session {
  const { key } = vectors;
  const keyPair = KeyPair.fromPrimitives({
    privateKey: key.privateKeyPem,
    publicKey: key.publicKeyPem,
  } as never);

  return {
    authorizationEpoch: { valueOf: () => 'genesis' },
    authorizationRevision: { valueOf: () => 0 },
    deviceCredentialKeyPair: keyPair,
    identity: { id: key.identityId },
    keyPair,
  } as unknown as Session;
}

describe(PigeonConversationsApi.name, () => {
  it.each(vectors.cases)(
    'sends the read-until proof for $name byte for byte like the node',
    async (vector: Case) => {
      const { derived, input } = vector;
      const { readProof } = input;
      const http = mock<HttpJsonClient>();
      // The signed path is the request path behind any API route prefix.
      const prefix = readProof.path.slice(
        0,
        readProof.path.indexOf('/conversations/'),
      );
      const signer = new RequestSigner(() => readProof.timestamp, prefix);
      const api = new PigeonConversationsApi(
        http,
        signer,
        new ConversationMapper(),
      );
      const path = `/conversations/${encodeURIComponent(
        input.conversationId,
      )}/messages/read-until`;

      expect(
        signer.payload('PUT', path, readProof.timestamp, readProof.body),
      ).toBe(derived.signingContent);

      await api.markReadUntil(
        sessionFromVectorKey(),
        input.conversationId,
        input.messageId,
      );

      expect(http.request).toHaveBeenCalledWith(path, {
        body: JSON.stringify(readProof.body),
        headers: expect.objectContaining({
          'X-Identity-Id': input.readerIdentityId,
          'X-Signature': readProof.signature,
          'X-Timestamp': `${readProof.timestamp}`,
        }),
        method: 'PUT',
      });
    },
  );
});
